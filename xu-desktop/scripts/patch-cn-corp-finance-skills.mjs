let n = 0;
for (const name of fs.readdirSync(DIR)) {
  if (!name.endsWith(".md")) continue;
  const slug = name.replace(/\.md$/, "");
  if (!CORP_SLUGS.has(slug)) continue;
  const p = path.join(DIR, name);
  if (slug === "finance-credit-risk-specialist") {
    fs.writeFileSync(p, CREDIT, "utf8");
    n += 1;
    continue;
  }
  let s = fs.readFileSync(p, "utf8");
  s = stripCollab(s);
  s = fixFront(s);
  if (slug === "finance-internal-auditor") s = patchInternalAuditorMeta(s);
  s = injectRed(s);
  s = replaceFlow(slug, s);
  s = addStampDutyToTax(s);
  fs.writeFileSync(p, s, "utf8");
  n += 1;
}

