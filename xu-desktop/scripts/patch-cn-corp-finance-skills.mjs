function stripCollab(s) {
  return s.replace(
    /\n?<!-- virmoor-software-collaboration:start -->[\s\S]*?<!-- virmoor-software-collaboration:end -->\n?/g,
    "\n",
  );
}

function fixFront(s) {
  s = s.replace(/catalogL1: "金融投资"/g, 'catalogL1: "企业财务"');
  s = s.replace(/industryZh: "金融数据"/g, 'industryZh: "企业财务"');
  s = s.replace(/请按软件研发 · [^"]+的职责[^"]*/g, "");
  s = s.replace(/需求信息不全时，软件研发 · [^"]+/g, "");
  s = s.replace(/, "请按软件研发[^"]*"/g, "");
  s = s.replace(/, "需求信息不全时，软件研发[^"]*"/g, "");
  s = s.replace(/\[\s*,/g, "[");
  s = s.replace(/,\s*,/g, ",");
  s = s.replace(/,\s*]/g, "]");
  return s;
}

function injectRed(s) {
  if (!s.includes("不得虚列或隐匿收入")) {
    s = s.replace(/- \*\*对照共享底座\*\*[^\n]+\n?/, `${RED_BLOCK}\n\n`);
  }
  if (s.includes("role-packs-src/_shared/finance-basics.md")) {
    s = s.replace(/- \*\*对照共享底座\*\*[^\n]+\n?/g, "");
  }
  return s;
}

function replaceFlow(slug, s) {
  const block = FLOW[slug];
  if (!block) return s;
  if (/🔄 工作流程[\s\S]*?(?=\n💬|\n## |$)/.test(s)) {
    return s.replace(/🔄 工作流程[\s\S]*?(?=\n💬|\n## )/, `${block}\n\n`);
  }
  return s;
}

