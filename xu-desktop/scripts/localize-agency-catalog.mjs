const BRAIN_ZH = { command: "指挥脑", work: "工作脑", code: "代码脑" };
const KIND_ZH = { worker: "员工", reviewer: "审核员", boss: "老板助理" };

function titleCaseWords(s) {
  return s
    .replace(/[-_]/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase())
    .replace(/\s+/g, " ")
    .trim();
}

function translateName(name, id) {
  if (NAME_ZH[name]) return NAME_ZH[name];
  const fromId = titleCaseWords(id.replace(/^(engineering|design|product|marketing|sales|finance|security|support|testing|strategy|specialized|academic|gis|healthcare)-/, ""));
  if (NAME_ZH[fromId]) return NAME_ZH[fromId];
  // last resort: keep readable Chinese-ish label from id
  return name;
}

function buildDescription(r, nameZh, divZh) {
  const brain = BRAIN_ZH[r.brainSlot] || r.brainSlot;
  const kind = KIND_ZH[r.roleKind] || r.roleKind;
  return `${divZh} · ${nameZh}。默认脑槽：${brain}；角色类型：${kind}。可在岗位库中微调人设提示词。`;
}

function buildPrompt(r, nameZh) {
  // Prefer keeping a previously rebuilt full prompt (no stub overwrite)
  if (r.prompt && r.prompt.includes("—— 完整岗位说明 ——") && !String(r.prompt).includes("参考来源：")) {
    return r.prompt;
  }
  return [
    `你是「${nameZh}」（岗位 id：${r.id}）。`,
    `所属部门：${DIV_ZH[r.division] || r.divisionZh || r.division}。`,
    `请严格按该岗位专长完成任务：输出可执行、可验收、用中文回复（除非用户要求其他语言）。`,
    `交付时说明假设、步骤与验收标准；不确定处先提问再动手。`,
  ].join("\n");
}

const raw = JSON.parse(fs.readFileSync(file, "utf8"));
const missing = [];
for (const r of raw.roles) {
  const nameZh = translateName(r.name, r.id);
  if (nameZh === r.name && !/[\u4e00-\u9fff]/.test(nameZh)) missing.push(r.name);
  const divZh = DIV_ZH[r.division] || r.divisionZh || r.division;
  r.nameZh = nameZh;
  r.divisionZh = divZh;
  r.description = buildDescription(r, nameZh, divZh);
  r.prompt = buildPrompt(r, nameZh);
}
raw.localizedAt = new Date().toISOString().slice(0, 10);
raw.count = raw.roles.length;
fs.writeFileSync(file, JSON.stringify(raw, null, 2) + "\n", "utf8");
