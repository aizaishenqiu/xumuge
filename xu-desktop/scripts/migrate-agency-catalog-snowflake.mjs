/**
 * One-time / idempotent: migrate agency catalog role ids to stable Snowflake IDs.
 * Also rewrites team packs, company staffing, industry workflow overrides.
 *
 * node scripts/migrate-agency-catalog-snowflake.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");

const CATALOG = path.join(ROOT, "src/office/agencyCatalog.generated.json");
const ID_MAP_OUT = path.join(ROOT, "src/office/agencyRoleIdMap.ts");
const TEAM_PACKS = path.join(ROOT, "src/office/agencyTeamPacks.ts");
const COMPANY_STAFFING = path.join(ROOT, "src/office/companyStaffing.ts");
const INDUSTRY_WORKFLOWS = path.join(ROOT, "src/office/industryWorkflows.ts");

const EPOCH = 1_704_067_200_000;
const WORKER_ID = 1n;
const DATACENTER_ID = 1n;
const SEQUENCE_BITS = 12n;
const WORKER_BITS = 5n;
const DATACENTER_BITS = 5n;
const MAX_SEQUENCE = (1n << SEQUENCE_BITS) - 1n;

function fnv1a64(input) {
  let hash = 0xcbf29ce484222325n;
  for (let i = 0; i < input.length; i++) {
    hash ^= BigInt(input.charCodeAt(i));
    hash = (hash * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return hash;
}

function stableSnowflakeFromKey(key) {
  const h = fnv1a64(String(key).trim());
  const ts = BigInt(EPOCH) + (h % 8_640_000_000_000n);
  const seq = h & MAX_SEQUENCE;
  const id =
    ((ts - BigInt(EPOCH)) << (DATACENTER_BITS + WORKER_BITS + SEQUENCE_BITS)) |
    (DATACENTER_ID << (WORKER_BITS + SEQUENCE_BITS)) |
    (WORKER_ID << SEQUENCE_BITS) |
    seq;
  return id.toString();
}

function cleanPrompt(prompt, oldId, nameZh) {
  if (!prompt) return prompt;
  let out = prompt;
  out = out.replace(new RegExp(`（岗位 id：${escapeReg(oldId)}）`, "g"), "");
  out = out.replace(new RegExp(`（岗位 id：software-company__${escapeReg(oldId)}）`, "g"), "");
  if (nameZh) {
    out = out.replace(
      new RegExp(`你是「${escapeReg(nameZh)}」（岗位 id：[^）]+）。`, "g"),
      `你是「${nameZh}」。`,
    );
  }
  out = out.replace(/你是「([^」]+)」（岗位 id：[^）]+）。/g, "你是「$1」。");
  return out;
}

function escapeReg(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function mapRoleIdsInTs(content, slugToSnow) {
  let out = content;
  const slugs = [...slugToSnow.keys()].sort((a, b) => b.length - a.length);
  for (const slug of slugs) {
    const snow = slugToSnow.get(slug);
    out = out.replaceAll(`"${slug}"`, `"${snow}"`);
  }
  return out;
}

function writeIdMap(slugToSnow) {
  const entries = [...slugToSnow.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slug, snow]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(snow)},`)
    .join("\n");

  const ts = `/** Auto-generated by scripts/migrate-agency-catalog-snowflake.mjs — do not edit. */
export const LEGACY_SLUG_TO_SNOWFLAKE: Record<string, string> = {
${entries}
};

export function resolveLegacyAgencyRoleId(id: string | null | undefined): string {
  if (!id) return "";
  return LEGACY_SLUG_TO_SNOWFLAKE[id] || id;
}
`;
  fs.writeFileSync(ID_MAP_OUT, ts, "utf8");
}

function legacySlugFromRole(role) {
  const rel = role.source || "";
  const base = rel.split("/").pop()?.replace(/\.md$/i, "") || role.id;
  if (role.division === "software-company") return `software-company__${base}`;
  return base;
}

function main() {
  const catalog = JSON.parse(fs.readFileSync(CATALOG, "utf8"));
  const slugToSnow = new Map();

  for (const role of catalog.roles) {
    const slug = legacySlugFromRole(role);
    const snow = stableSnowflakeFromKey(slug);
    slugToSnow.set(slug, snow);
    role.id = snow;
    role.prompt = cleanPrompt(role.prompt, slug, role.nameZh || role.name);
  }

  catalog.version = (catalog.version || 1) + 1;
  catalog.idScheme = "snowflake";
  fs.writeFileSync(CATALOG, JSON.stringify(catalog, null, 2) + "\n", "utf8");
  console.log("catalog roles migrated:", catalog.roles.length);

  writeIdMap(slugToSnow);

  for (const file of [TEAM_PACKS, COMPANY_STAFFING, INDUSTRY_WORKFLOWS]) {
    const raw = fs.readFileSync(file, "utf8");
    const next = mapRoleIdsInTs(raw, slugToSnow);
    if (next !== raw) {
      fs.writeFileSync(file, next, "utf8");
      console.log("updated", path.relative(ROOT, file));
    }
  }

  console.log("done — agencyRoleIdMap.ts written");
}

main();
