function needsLegacyIdMigration(id: string): boolean {
  return id.startsWith("emp_") || id.startsWith("seed_");
}

function parsePaths(raw: string): string[] {
  try {
    const v = JSON.parse(raw);
    return Array.isArray(v) ? v.map(String) : [];
  } catch {
    return [];
  }
}

function fromRow(row: EmployeeRowDto): Employee {
  const agentRoleId = resolveLegacyAgencyRoleId(row.agentRoleId || "");
  return {
    id: row.id,
    employeeNo: row.employeeNo || "",
    name: row.name,
    age: typeof row.age === "number" && row.age > 0 ? row.age : 28,
    role: row.role || "员工",
    avatarId: row.avatarId || "classic",
    deskIndex: row.deskIndex ?? null,
    status: (row.status as EmployeeStatus) || "idle",
    createdAt: row.createdAt,
    workspaceRoot: row.workspaceRoot ?? null,
    readExtraPaths: parsePaths(row.readExtraPaths || "[]"),
    allowNetworkExfil: row.allowNetworkExfil === true,
    driveMode: row.driveMode === "sdk" || row.driveMode === "input_control" ? row.driveMode : "off",
    gender: row.gender === "female" ? "female" : "male",
    roleKind: row.roleKind === "reviewer" || row.roleKind === "boss" ? row.roleKind : "worker",
    brainSlot:
      row.brainSlot === "command" || row.brainSlot === "code" ? row.brainSlot : "work",
    outfit: row.outfit || "casual",
    hairStyle: row.hairStyle || (row.gender === "female" ? "bob" : "short"),
    agentRoleId,
    aiModel: row.aiModel || "",
    aiBaseUrl: row.aiBaseUrl || "",
    aiVisionModel: row.aiVisionModel || "",
    apiSource:
      row.apiSource === "local" || row.apiSource === "remote" ? row.apiSource : "inherit",
    remotePresetId: row.remotePresetId || "",
    codeEditorSurface: normalizeCodeEditorSurface(row.codeEditorSurface),
    ...(() => {
      const bind = loadRoleVoiceBind(row.id);
      const byRole = agentRoleId ? loadRoleVoiceBind(agentRoleId) : {};
      return {
        voiceToneId: bind.voiceToneId || byRole.voiceToneId,
        ttsProviderHint: bind.ttsProviderHint || byRole.ttsProviderHint,
      };
    })(),
  };
}

function normalizeCodeEditorSurface(raw: unknown): CodeEditorSurface {
  const s = String(raw || "inherit");
  if (s === "builtin" || s === "external") return s;
  return "inherit";
}

