export function nextFreeDeskIndex(deskCount: number, employees = readEmployees()): number | null {
  const used = new Set(employees.map((e) => e.deskIndex).filter((n): n is number => n != null));
  for (let i = 0; i < deskCount; i++) {
    if (!used.has(i)) return i;
  }
  return null;
}

export function listOccupiedDeskIndices(employees = readEmployees()): number[] {
  return [
    ...new Set(employees.map((e) => e.deskIndex).filter((n): n is number => n != null)),
  ].sort((a, b) => a - b);
}

export async function unbindEmployeesFromDesks(indices: number[]): Promise<number> {
  const set = new Set(indices.filter((n) => Number.isFinite(n)));
  if (set.size === 0) return 0;
  const affected = cache.filter((e) => e.deskIndex != null && set.has(e.deskIndex));
  if (affected.length === 0) return 0;
  for (const emp of affected) {
    await invoke("xu_upsert_employee", { employee: toRow({ ...emp, deskIndex: null }) });
  }
  await loadEmployees();
  window.dispatchEvent(new CustomEvent("xu-employees-changed"));
  return affected.length;
}

export async function buildPolicyPreamble(emp: Employee, taskHint?: string): Promise<string> {
  const writeRoot = emp.workspaceRoot?.trim() || "(未设置)";
  const readExtra =
    emp.readExtraPaths.filter(Boolean).length > 0
      ? emp.readExtraPaths.filter(Boolean).map((p) => `- ${p}`).join("\n")
      : "- （无额外只读路径）";
  const exfil = emp.allowNetworkExfil
    ? "允许在完成任务必要时使用网络；仍禁止泄露密钥/凭据。"
    : "禁止将工作区内源码、机密或文件内容上传/粘贴到外网、公开聊天或无关服务（禁外传）。";
  const agency = getAgencyRole(emp.agentRoleId);
  let agencyBlock = "";
  if (agency) {
    const prompt = await ensureAgencyRolePrompt(agency.id);
    const personaRole = { ...agency, prompt };
    agencyBlock = `\n【Agency 短人设 · ${personaRole.nameZh || personaRole.name}】\n${buildAgencyShortPersona(personaRole, { task: taskHint || "" })}\n`;
    const pack = buildRoleAgencyPack(agency);
    if (pack) agencyBlock += `\n${pack}\n`;
    try {
      const { buildEmployeeCurriculumHint } = await import("../training/employeeHints");
      const cur = await buildEmployeeCurriculumHint(agency.id, emp.id);
      if (cur) agencyBlock += `\n${cur}\n`;
    } catch {
      /* ignore */
    }
  }

  const { buildOralPersonaBlock } = await import("./assistantOralPersona");
  agencyBlock += buildOralPersonaBlock();

  return [
    `【虚募阁员工策略 · ${emp.name} · 策略约束非 OS 沙箱】`,
    `你是「${emp.name}」（职责：${emp.role}，角色：${emp.roleKind}，脑槽：${emp.brainSlot}）。必须遵守：`,
    `1. 可写范围：仅可在以下目录内创建/编辑/删除文件：${writeRoot}`,
    `2. 只读范围：工作区以外默认只读；额外只读路径：`,
    readExtra,
    `3. 外传：${exfil}`,
    `4. 不得修改工作区外的系统配置、全局密钥或无关仓库。`,
    `5. 若任务需要越界，先说明原因并停止，等待 Boss 放宽边界。`,
    ideOpenPolicyLine(resolveEmpPolicySurface(emp)),
    agencyBlock,
    `【任务】`,
  ]
    .filter((s) => s !== "")
    .join("\n");
}

export async function composeEmployeeTaskMessage(
  emp: Employee,
  task: string,
  extraHints?: string,
): Promise<string> {
  const t = task.trim();
  const base = `${await buildPolicyPreamble(emp, t)}\n${t}`;
  const hints = extraHints?.trim();
  return hints ? `${base}\n\n${hints}` : base;
}

export function employeeBoundarySummary(emp: Employee): string {
  if (!emp.workspaceRoot) return "未设置工作区（不可派活）";
  const exfil = emp.allowNetworkExfil ? "可外传" : "禁外传";
  return `写：${emp.workspaceRoot} · ${exfil} · ${emp.brainSlot}`;
}

