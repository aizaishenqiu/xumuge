export async function bootstrapEmployees(): Promise<Employee[]> {
  const local = readLocalStorageEmployees();
  let rows = await invoke<EmployeeRowDto[]>("xu_bootstrap_employees", {
    payload: {
      employees: local.map(toRow),
      seedIfEmpty: true,
    },
  });
  cache = await runEmployeeMigrationsOnce(rows.map(fromRow));
  cache = await repairEmployeesWithRoleAsName(cache);
  bootstrapped = true;
  if (local.length > 0) {
    try {
      localStorage.removeItem(STORAGE_KEY);
    } catch {
      /* ignore */
    }
  }
  try {
    if (!sessionStorage.getItem("xu.coldStart.busyReset")) {
      const summary = await invoke<{
        scanned: number;
        resumed: number;
        meeting: number;
        skipped: number;
        errors: string[];
      }>("xu_resume_interrupted_dispatches", { maxResume: 6 });
      sessionStorage.setItem("xu.coldStart.busyReset", "1");
      const fresh = await invoke<EmployeeRowDto[]>("xu_list_employees");
      cache = fresh.map(fromRow);
      if ((summary.resumed ?? 0) > 0 || (summary.meeting ?? 0) > 0) {
        console.info("[xu] resume interrupted dispatches", summary);
      }
    }
  } catch (e) {
    console.warn("[xu] resume interrupted dispatches failed", e);
  }
  window.dispatchEvent(new CustomEvent("xu-employees-changed"));
  return cache;
}

export async function loadEmployees(): Promise<Employee[]> {
  if (!bootstrapped) return bootstrapEmployees();
  const rows = await invoke<EmployeeRowDto[]>("xu_list_employees");
  cache = await repairEmployeesWithRoleAsName(rows.map(fromRow));
  return cache;
}

