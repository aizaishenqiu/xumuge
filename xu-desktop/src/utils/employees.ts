export async function saveEmployee(emp: Employee): Promise<void> {
  await invoke("xu_upsert_employee", { employee: toRow(emp) });
  if (emp.voiceToneId || emp.ttsProviderHint) {
    saveRoleVoiceBind(emp.id, {
      voiceToneId: emp.voiceToneId,
      ttsProviderHint: emp.ttsProviderHint ?? "auto",
    });
    if (emp.agentRoleId) {
      saveRoleVoiceBind(emp.agentRoleId, {
        voiceToneId: emp.voiceToneId,
        ttsProviderHint: emp.ttsProviderHint ?? "auto",
      });
    }
  }
  await loadEmployees();
  window.dispatchEvent(new CustomEvent("xu-employees-changed"));
}

export async function saveEmployeesBatch(emps: Employee[]): Promise<void> {
  if (!emps.length) return;
  const prevById = new Map(cache.map((e) => [e.id, toRow(e)]));
  const dirty: Employee[] = [];
  for (const emp of emps) {
    const row = toRow(emp);
    const prev = prevById.get(emp.id);
    if (!prev || JSON.stringify(prev) !== JSON.stringify(row)) {
      dirty.push(emp);
    }
  }
  if (!dirty.length) return;
  if (dirty.length === 1) {
    await invoke("xu_upsert_employee", { employee: toRow(dirty[0]) });
  } else {
    await invoke("xu_upsert_employees_batch", {
      employees: dirty.map(toRow),
    });
  }
  await loadEmployees();
  window.dispatchEvent(new CustomEvent("xu-employees-changed"));
}

