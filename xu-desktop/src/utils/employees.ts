const ensureRoleLocks = new Map<string, Promise<Employee>>();

/** Create (or reuse) an employee for an agency catalog role. */
export async function ensureEmployeeForRole(
  role: import("../office/agencyRoles").AgencyRole,
): Promise<Employee> {
  const roleKey = resolveLegacyAgencyRoleId(role.id);
  const pending = ensureRoleLocks.get(roleKey);
  if (pending) return pending;

  const job = (async () => {
    await loadEmployees();
    const existing = findEmployeeByAgentRoleId(role.id);
    if (existing) return existing;
    const gender: Gender = /女|design|ux|content|marketing/i.test(`${role.nameZh}${role.id}`)
      ? "female"
      : "male";
    return addEmployee({
      role: role.nameZh || role.name,
      agentRoleId: role.id,
      roleKind: role.roleKind,
      brainSlot: role.brainSlot,
      gender,
      avatarId: gender === "female" ? "rose" : "classic",
      deskIndex: null,
      workspaceRoot: null,
      readExtraPaths: [],
      allowNetworkExfil: false,
      driveMode: "off",
      apiSource: "inherit",
    });
  })();

  ensureRoleLocks.set(roleKey, job);
  try {
    return await job;
  } finally {
    ensureRoleLocks.delete(roleKey);
  }
}

/** Ensure roster covers matched agency roles; returns employees in role-id order. */
export async function ensureEmployeesForRoleIds(roleIds: string[]): Promise<Employee[]> {
  const { ensureAgencyCatalog, getAgencyRole } = await import("../office/agencyRoles");
  await ensureAgencyCatalog();
  const out: Employee[] = [];
  const seen = new Set<string>();
  for (const rid of roleIds) {
    const role = getAgencyRole(rid);
    if (!role || role.roleKind === "boss") continue;
    const emp = await ensureEmployeeForRole(role);
    if (seen.has(emp.id)) continue;
    seen.add(emp.id);
    out.push(emp);
  }
  return out;
}

export async function addEmployee(input: EmployeeInput): Promise<Employee> {
  const roleKind = input.roleKind ?? "worker";
  const persona: VirtualPersona = generateVirtualPersona({
    gender: input.gender,
    roleKind,
    seed: nextSnowflakeId(),
  });
  const emp: Employee = {
    id: nextSnowflakeId(),
    employeeNo: input.employeeNo?.trim() || (await nextEmployeeNo()),
    name: (input.name || "").trim() || persona.name,
    age: input.age && input.age > 0 ? input.age : persona.age,
    role: input.role.trim() || "员工",
    avatarId: input.avatarId || "classic",
    deskIndex: input.deskIndex,
    status: "idle",
    createdAt: Date.now(),
    workspaceRoot: input.workspaceRoot ?? null,
    readExtraPaths: input.readExtraPaths ?? [],
    allowNetworkExfil: input.allowNetworkExfil === true,
    driveMode: input.driveMode ?? "off",
    gender: input.gender ?? persona.gender,
    roleKind,
    brainSlot: input.brainSlot ?? "work",
    outfit: input.outfit ?? "casual",
    hairStyle: input.hairStyle ?? ((input.gender ?? persona.gender) === "female" ? "bob" : "short"),
    agentRoleId: resolveLegacyAgencyRoleId(input.agentRoleId ?? ""),
    aiModel: (input.aiModel ?? "").trim(),
    aiBaseUrl: (input.aiBaseUrl ?? "").trim(),
    aiVisionModel: (input.aiVisionModel ?? "").trim(),
    apiSource:
      input.apiSource === "local" || input.apiSource === "remote" ? input.apiSource : "inherit",
    remotePresetId: (input.remotePresetId ?? "").trim(),
    codeEditorSurface: normalizeCodeEditorSurface(input.codeEditorSurface ?? "inherit"),
  };
  await saveEmployee(emp);
  return emp;
}

const EMPLOYEE_NO_SEQ_KEY = "xu.employee_no_seq";

export async function nextEmployeeNo(): Promise<string> {
  let seq = 1;
  try {
    const raw = await invoke<string | null>("xu_get_setting", { key: EMPLOYEE_NO_SEQ_KEY });
    if (raw != null && raw !== "") {
      const n = Number(raw);
      if (Number.isFinite(n) && n >= 0) seq = Math.floor(n) + 1;
    }
  } catch {
    try {
      const local = Number(localStorage.getItem(EMPLOYEE_NO_SEQ_KEY) || "0");
      if (Number.isFinite(local) && local >= 0) seq = Math.floor(local) + 1;
    } catch {
      /* ignore */
    }
  }
  try {
    await invoke("xu_set_setting", { key: EMPLOYEE_NO_SEQ_KEY, value: String(seq) });
  } catch {
    try {
      localStorage.setItem(EMPLOYEE_NO_SEQ_KEY, String(seq));
    } catch {
      /* ignore */
    }
  }
  return `F${String(seq).padStart(4, "0")}`;
}

