function readLocalStorageEmployees(): Employee[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed
      .filter((e): e is Partial<Employee> & { id: string; name: string } =>
        Boolean(e && typeof e === "object" && typeof (e as Employee).id === "string" && typeof (e as Employee).name === "string"),
      )
      .map(normalizeLocal);
  } catch {
    return [];
  }
}

async function remapProjectEmployeeIds(idMap: Record<string, string>): Promise<void> {
  try {
    const raw = await invoke<string | null>("xu_get_setting", { key: PROJECTS_DB_KEY });
    if (!raw) return;
    const list = JSON.parse(raw) as Array<{ employeeIds?: string[] }>;
    if (!Array.isArray(list)) return;
    let changed = false;
    for (const p of list) {
      if (!Array.isArray(p.employeeIds)) continue;
      const next = p.employeeIds.map((id) => idMap[id] || id);
      if (JSON.stringify(next) !== JSON.stringify(p.employeeIds)) {
        p.employeeIds = next;
        changed = true;
      }
    }
    if (changed) {
      await invoke("xu_set_setting", { key: PROJECTS_DB_KEY, value: JSON.stringify(list) });
    }
  } catch {
    /* ignore */
  }
}

async function migrateEmployeesSchema(rows: Employee[]): Promise<Employee[]> {
  const idMap: Record<string, string> = {};
  const patches: Employee[] = [];

  for (const emp of rows) {
    let next = { ...emp };
    let dirty = false;

    if (needsLegacyIdMigration(emp.id)) {
      const newId = nextSnowflakeId();
      idMap[emp.id] = newId;
      await invoke("xu_remap_employee_id", { oldId: emp.id, newId });
      next.id = newId;
      dirty = true;
    }

    const resolvedRole = resolveLegacyAgencyRoleId(emp.agentRoleId);
    if (resolvedRole !== emp.agentRoleId) {
      next.agentRoleId = resolvedRole;
      dirty = true;
    }

    if (!next.employeeNo?.trim()) {
      next.employeeNo = await nextEmployeeNo();
      dirty = true;
    }

    const needsPersona =
      !next.age ||
      next.age < 18 ||
      looksAutoGeneratedName(next.name) ||
      ["助手", "工程师", "导师", "审码"].includes(next.name) ||
      (next.role.trim() && next.name.trim() === next.role.trim());
    if (needsPersona) {
      const persona = generateVirtualPersona({
        roleKind: next.roleKind,
        seed: `${next.id}:${next.employeeNo}`,
      });
      next.name = persona.name;
      next.gender = persona.gender;
      next.age = persona.age;
      dirty = true;
    }

    if (dirty) {
      await invoke("xu_upsert_employee", { employee: toRow(next) });
      patches.push(next);
    } else {
      patches.push(next);
    }
  }

  if (Object.keys(idMap).length > 0) {
    await remapProjectEmployeeIds(idMap);
  }

  const fresh = await invoke<EmployeeRowDto[]>("xu_list_employees");
  return fresh.map(fromRow);
}

/** 姓名误存为岗位名时，补全虚构中文名（职务 · 姓名 展示） */
async function repairEmployeesWithRoleAsName(list: Employee[]): Promise<Employee[]> {
  const fixes: Employee[] = [];
  for (const emp of list) {
    const role = emp.role.trim();
    const name = emp.name.trim();
    if (!role || name !== role) continue;
    const persona = generateVirtualPersona({
      gender: emp.gender,
      roleKind: emp.roleKind,
      seed: `${emp.id}:${emp.employeeNo}:display-name`,
    });
    fixes.push({
      ...emp,
      name: persona.name,
      age: emp.age > 0 ? emp.age : persona.age,
    });
  }
  if (!fixes.length) return list;
  if (fixes.length === 1) {
    await invoke("xu_upsert_employee", { employee: toRow(fixes[0]) });
  } else {
    await invoke("xu_upsert_employees_batch", { employees: fixes.map(toRow) });
  }
  const fresh = await invoke<EmployeeRowDto[]>("xu_list_employees");
  const next = fresh.map(fromRow);
  window.dispatchEvent(new CustomEvent("xu-employees-changed"));
  return next;
}

async function runEmployeeMigrationsOnce(rows: Employee[]): Promise<Employee[]> {
  try {
    const done = await invoke<string | null>("xu_get_setting", { key: MIGRATION_KEY });
    if (done === "1") {
      return rows.map((e) => {
        const agentRoleId = resolveLegacyAgencyRoleId(e.agentRoleId);
        return agentRoleId === e.agentRoleId ? e : { ...e, agentRoleId };
      });
    }
    const migrated = await migrateEmployeesSchema(rows);
    await invoke("xu_set_setting", { key: MIGRATION_KEY, value: "1" });
    return migrated;
  } catch {
    return rows;
  }
}

